"""Exports the demo database as complete SQL scripts (tables + all data) for PostgreSQL and MySQL.

    python database/export_sql.py

Creates database/seahorse_demo_postgresql.sql and database/seahorse_demo_mysql.sql.
"""
import os
import sqlite3
import sys
from datetime import date, datetime

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
from sqlalchemy.dialects import mysql, postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from seahorse import create_app  # noqa: E402
from seahorse.extensions import db  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "seahorse_demo.db")


def literal(v, dialect):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return str(v)
    s = str(v).replace("\\\\", "\\\\\\\\") if dialect == "mysql" else str(v)
    return "'" + s.replace("'", "''") + "'"


def export(name, dialect_obj, quote):
    app = create_app({"SQLALCHEMY_DATABASE_URI": "sqlite://"})
    with app.app_context():
        tables = db.metadata.sorted_tables
        src = sqlite3.connect(SRC)
        out = [f"-- Seahorse Ride demo database for {name}: every table and every row.",
               "-- Generated by database/export_sql.py from seahorse_demo.db. Demo passwords: Password123",
               ""]
        if name == "MySQL":
            out += ["SET NAMES utf8mb4;", "SET FOREIGN_KEY_CHECKS=0;", ""]
        for t in tables:
            out.append(f"DROP TABLE IF EXISTS {quote(t.name)}{' CASCADE' if name == 'PostgreSQL' else ''};")
        out.append("")
        for t in tables:
            ddl = str(CreateTable(t).compile(dialect=dialect_obj)).strip()
            if name == "MySQL":
                ddl += " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
            out.append(ddl + ";")
            for ix in t.indexes:
                out.append(str(CreateIndex(ix).compile(dialect=dialect_obj)).strip() + ";")
            out.append("")
        dial = "mysql" if name == "MySQL" else "pg"
        for t in tables:
            cols = [c.name for c in t.columns]
            bool_cols = {c.name for c in t.columns if c.type.python_type is bool}
            rows = src.execute(f'SELECT {", ".join(chr(34) + c + chr(34) for c in cols)} FROM "{t.name}"').fetchall()
            if not rows:
                continue
            out.append(f"-- {t.name}: {len(rows)} row(s)")
            for r in rows:
                vals = []
                for c, v in zip(cols, r):
                    if c in bool_cols and v is not None:
                        vals.append(("TRUE" if v else "FALSE") if dial == "pg" else ("1" if v else "0"))
                    else:
                        vals.append(literal(v, dial))
                out.append(f"INSERT INTO {quote(t.name)} ({', '.join(quote(c) for c in cols)}) VALUES ({', '.join(vals)});")
            out.append("")
        # Migration marker, so `python app.py` / `flask db upgrade` knows these tables are already up to date.
        head = src.execute("SELECT version_num FROM alembic_version").fetchone()[0]
        out += [f"DROP TABLE IF EXISTS {quote('alembic_version')};",
                f"CREATE TABLE {quote('alembic_version')} ({quote('version_num')} VARCHAR(32) NOT NULL PRIMARY KEY);",
                f"INSERT INTO {quote('alembic_version')} ({quote('version_num')}) VALUES ('{head}');", ""]
        if name == "PostgreSQL":
            for t in tables:
                if "id" in t.columns and t.columns["id"].autoincrement is not False and len(t.primary_key.columns) == 1 \
                        and t.columns["id"].type.python_type is int:
                    out.append(f"SELECT setval(pg_get_serial_sequence('{quote(t.name)}', 'id'), "
                               f"COALESCE((SELECT MAX(id) FROM {quote(t.name)}), 1));")
        else:
            out.append("SET FOREIGN_KEY_CHECKS=1;")
        path = os.path.join(HERE, f"seahorse_demo_{name.lower()}.sql")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(out) + "\n")
        print("Wrote", path)


export("PostgreSQL", postgresql.dialect(), lambda n: f'"{n}"')
export("MySQL", mysql.dialect(), lambda n: f"`{n}`")
